#!/usr/bin/env python3
"""config_fields.py — AsyncRAT config field extraction from de4dot output.

Plan §5-6: extracts specific AsyncRAT config fields after de4dot cleanup.
Target fields: Hosts, Ports, AESKey, Mutex, InstallDir, Certificate, Pastebin, Telegram.

Usage:
    python3 config_fields.py <path_to_de4dot_output> [--output <json>]
"""

import argparse
import json
import re
import sys
from pathlib import Path


# Known AsyncRAT config field names and their typical patterns
CONFIG_FIELDS = {
    "hosts": [rb"host[:\s]+([A-Za-z0-9.\-]{3,255})", rb"server[:\s]+([A-Za-z0-9.\-]{3,255})"],
    "ports": [rb"port[:\s]+(\d{1,5})", rb"listen[:\s]+(\d{1,5})"],
    "aes_key": [rb"aes[_-]?key[:\s]+([A-Za-z0-9+/=]{16,32})", rb"cipher[_-]?key[:\s]+([A-Za-z0-9+/=]{16,32})"],
    "mutex": [rb"mutex[:\s]+([A-Za-z0-9_.\-]{3,64})", rb"mut[:\s]+([A-Za-z0-9_.\-]{3,64})"],
    "install_dir": [
        rb"installdir[:\s]+([A-Za-z0-9._\-\\/]{3,255})",
        rb"directory[:\s]+([A-Za-z0-9._\-\\/]{3,255})",
    ],
    "certificate": [rb"cert[:\s]+([A-Za-z0-9_/= .\-]{3,255})", rb"pem[:\s]+([A-Za-z0-9_/= .\-]{3,255})"],
    "pastebin": [rb"paste[_-]?bin[:\s]+(https?://[^\s]{10,})"],
    "telegram": [rb"telegram[_-]?api[_-]?id[:\s]*([0-9]{4,9})", rb"telegram[_-]?bot[_-]?token[:\s]*([A-Za-z0-9:]{10,})"],
}


def find_config_file(res_dir: Path) -> Path | None:
    """Find config.json generated by de4dot in the resource directory."""
    candidates = list(res_dir.rglob("config.json"))
    if not candidates:
        return None
    return candidates[0]


def parse_config_json(config_path: Path) -> dict:
    """Parse the de4dot-extracted config.json file."""
    try:
        text = config_path.read_text(encoding="utf-8", errors="replace")
    except Exception:
        return {}

    # Extract the first JSON object found
    match = re.search(r"\{\s*.*?\s*\}", text, re.DOTALL)
    if not match:
        return {}

    raw = match.group(0)
    try:
        data = json.loads(raw)
        if isinstance(data, dict):
            return data
    except (json.JSONDecodeError, ValueError):
        pass

    # Fallback: extract key-value pairs with quoted keys
    result = {}
    pairs = re.findall(r'"(\w+)"\s*:\s*"((?:[^"\\]|\\.)*)"', raw)
    for key, value in pairs:
        result[key] = value
    return result


def decode_base64_safe(text: str) -> str | None:
    """Attempt base64 decode, return decoded string or None."""
    import base64
    try:
        decoded = base64.b64decode(text).decode("utf-8", errors="replace")
        return decoded
    except Exception:
        return None


def extract_config_fields(pe_path: Path) -> dict:
    """Extract AsyncRAT config fields from a .NET assembly.

    Tries multiple approaches:
    1. de4dot output config.json if present
    2. Raw resource search for known config patterns
    3. String pattern matching in the binary
    """
    config = {}

    # Approach 1: de4dot-extracted config.json
    if pe_path.is_dir():
        config_json = find_config_json(pe_path)
        if config_json:
            parsed = parse_config_json(config_json)
            config.update(parsed)

    # Approach 2: binary pattern matching
    if pe_path.is_file():
        try:
            data = pe_path.read_bytes()
            for field, patterns in CONFIG_FIELDS.items():
                if field in config:  # already found
                    continue
                for pattern in patterns:
                    m = re.search(pattern, data.decode("utf-8", errors="ignore"), re.IGNORECASE)
                    if m:
                        config[field] = m.group(1).strip()
                        break
        except Exception:
            pass

    # Approach 3: decode any base64-encoded values
    for field in list(config.keys()):
        if isinstance(config[field], str):
            decoded = decode_base64_safe(config[field])
            if decoded and len(decoded) > len(config[field]) * 0.5:
                config[field] = decoded

    return config


def main():
    ap = argparse.ArgumentParser(description="Extract AsyncRAT config fields")
    ap.add_argument("sample", help="Path to .NET assembly or de4dot output directory")
    ap.add_argument("--output", "-o", help="Output JSON file path")
    args = ap.parse_args()

    src = Path(args.sample)
    if not src.exists():
        print(f"ERROR: not found: {src}", file=sys.stderr)
        sys.exit(1)

    config = extract_config_fields(src)

    if config:
        print(f"Extracted {len(config)} config field(s) from {src}:")
        for key, value in config.items():
            print(f"  {key}: {value}")
    else:
        print(f"No config fields found in {src}")
        print("  - Try running de4dot first: https://github.com/de4dot/de4dot")
        print("  - Or ensure the path points to a de4dot output directory")

    # Write output if requested
    if args.output and config:
        out_path = Path(args.output)
        out_path.write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
        print(f"\nConfig written to: {out_path}")


if __name__ == "__main__":
    main()